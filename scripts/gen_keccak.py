#!/usr/bin/env python3
"""Generate boot/keccak_rv32.c: Keccak-f[1600] for RV32.

One fully unrolled round (theta + rho + pi + chi + iota fused, out of place
A -> E -> A ...) on 64-bit lanes held as explicit 32-bit (lo, hi) halves.
Only one round is unrolled so the loop body (~2 KB) fits VexRiscv's 4 KB
I-cache; the state ping-pongs between the caller's buffer and a stack copy.

usage: gen_keccak.py <output.c> [--fused]
"""
import sys

# rho rotation offsets, lane index i = x + 5*y
RHO = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39,
       41, 45, 15, 21, 8, 18, 2, 61, 56, 14]
RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808a,
      0x8000000080008000, 0x000000000000808b, 0x0000000080000001,
      0x8000000080008081, 0x8000000000008009, 0x000000000000008a,
      0x0000000000000088, 0x0000000080008009, 0x000000008000000a,
      0x000000008000808b, 0x800000000000008b, 0x8000000000008089,
      0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
      0x000000000000800a, 0x800000008000000a, 0x8000000080008081,
      0x8000000000008080, 0x0000000080000001, 0x8000000080008008]


def rot(lo, hi, r, olo, ohi):
    """C statements: (olo, ohi) = rotl64((lo, hi), r)."""
    if r == 0:
        return [f"{olo} = {lo}; {ohi} = {hi};"]
    if r == 32:
        return [f"{olo} = {hi}; {ohi} = {lo};"]
    if r > 32:
        lo, hi, r = hi, lo, r - 32
    return [f"{olo} = ({lo} << {r}) | ({hi} >> {32 - r});",
            f"{ohi} = ({hi} << {r}) | ({lo} >> {32 - r});"]


def parity_from_state():
    out = []
    for x in range(5):
        for h in (0, 1):
            terms = " ^ ".join(f"s[{2 * (x + 5 * y) + h}]" for y in range(5))
            out.append(f"c{x}{'lh'[h]} = {terms};")
    return out


def round_body(fused=False):
    out = []
    # theta: column parities C[x] (fused: already in c* from the last round)
    if not fused:
        out += parity_from_state()
    # D[x] = C[x-1] ^ rotl1(C[x+1])
    for x in range(5):
        p, n = (x - 1) % 5, (x + 1) % 5
        out.append(f"d{x}l = c{p}l ^ ((c{n}l << 1) | (c{n}h >> 31));")
        out.append(f"d{x}h = c{p}h ^ ((c{n}h << 1) | (c{n}l >> 31));")
    # per output row Y: gather the 5 pi sources, rho, then chi
    for Y in range(5):
        for X in range(5):
            # B[X, Y] = rotl(A[x, y] ^ D[x], rho[x, y]) with X = y,
            # Y = (2x + 3y) % 5  ->  y = X, x = 3 * (Y - 3X) % 5
            y, x = X, (3 * (Y - 3 * X)) % 5
            i = x + 5 * y
            out.append(f"tl = s[{2 * i}] ^ d{x}l; th = s[{2 * i + 1}] ^ d{x}h;")
            out += rot("tl", "th", RHO[i], f"b{X}l", f"b{X}h")
        for X in range(5):
            o = 2 * (X + 5 * Y)
            n1, n2 = (X + 1) % 5, (X + 2) % 5
            for h in "lh":
                v = f"b{X}{h} ^ (~b{n1}{h} & b{n2}{h})"
                if X == 0 and Y == 0:
                    # iota on lane (0,0) before it enters the parity
                    v = f"({v}) ^ rc_{'lo' if h == 'l' else 'hi'}[r]"
                if not fused:
                    out.append(f"d[{o + (h == 'h')}] = {v};")
                else:
                    acc = f"e{X}{h}"
                    out.append(f"tl = {v}; d[{o + (h == 'h')}] = tl; "
                               + (f"{acc} = tl;" if Y == 0 else f"{acc} ^= tl;"))
    if fused:
        for x in range(5):
            for h in "lh":
                out.append(f"c{x}{h} = e{x}{h};")
    return out


def main(path, fused=False):
    body = "\n        ".join(round_body(fused))
    pre = "\n    ".join(parity_from_state()) if fused else ""
    edecl = ("uint32_t e0l, e0h, e1l, e1h, e2l, e2h, e3l, e3h, e4l, e4h;"
             if fused else "")
    rcl = ", ".join(f"0x{c & 0xffffffff:08x}u" for c in RC)
    rch = ", ".join(f"0x{c >> 32:08x}u" for c in RC)
    src = f"""/*
 * keccak_rv32.c - Keccak-f[1600] permutation for RV32 (generated by
 * scripts/gen_keccak.py, do not edit).
 *
 * Replaces wolfCrypt's BlockSha3() (sha3.c is compiled with
 * -DWOLFSSL_RISCV_ASM, which only removes its own permutation). SHA-3 /
 * SHAKE is the core of ML-KEM and ML-DSA; wolfCrypt's generic version works
 * on 64-bit words, which this 32-bit core emulates. Here every lane is an
 * explicit (lo, hi) pair of 32-bit words, theta/rho/pi/chi/iota are fused
 * into one round that reads the state twice and writes it once, and only
 * one round is unrolled so the loop fits VexRiscv's 4 KB I-cache.
 */
#include <stdint.h>

#include <wolfssl/wolfcrypt/settings.h>
#include <wolfssl/wolfcrypt/types.h>

void BlockSha3(word64 *state);

static const uint32_t rc_lo[24] = {{ {rcl} }};
static const uint32_t rc_hi[24] = {{ {rch} }};

void BlockSha3(word64 *state)
{{
    uint32_t tmp[50];
    uint32_t *s = (uint32_t *)state, *d = tmp;
    uint32_t c0l, c0h, c1l, c1h, c2l, c2h, c3l, c3h, c4l, c4h;
    uint32_t d0l, d0h, d1l, d1h, d2l, d2h, d3l, d3h, d4l, d4h;
    uint32_t b0l, b0h, b1l, b1h, b2l, b2h, b3l, b3h, b4l, b4h;
    uint32_t tl, th;
    {edecl}

    {pre}
    for (int r = 0; r < 24; r++) {{
        {body}
        uint32_t *t = s; s = d; d = t;   /* 24 rounds: ends back in state */
    }}
}}
"""
    open(path, "w").write(src)
    print("wrote", path)


if __name__ == "__main__":
    # --fused: theta parities accumulated from the previous round's chi
    # output instead of re-loading the state (saves 50 loads per round).
    main(sys.argv[1], fused="--fused" in sys.argv[2:])
