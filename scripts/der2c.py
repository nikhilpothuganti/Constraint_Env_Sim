#!/usr/bin/env python3
"""Convert the device's DER certificates/key into a C header for the firmware.

usage: der2c.py <certs/mldsaNN dir> <output .h> [key file name]
Embeds: ca-cert.der (trust anchor), server-cert.der (pinned server
certificate, see dtls_client.c), client-cert.der and the private key
(default client-key.der; e.g. client-key-priv.der for the expanded-only
ML-DSA format, which loads without re-running key generation).
"""
import pathlib
import sys

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
keyfile = sys.argv[3] if len(sys.argv) > 3 else "client-key.der"
items = [("ca_cert_der", "ca-cert.der", "CA that signed the server cert (trust anchor)"),
         ("server_cert_der", "server-cert.der", "pinned server certificate (trusted peer)"),
         ("client_cert_der", "client-cert.der", "this device's certificate"),
         ("client_key_der", keyfile, "this device's ML-DSA private key (PKCS#8, %s)" % keyfile)]

lines = [
    "/* Generated by scripts/der2c.py from %s - do not edit. */" % src.name,
    "#ifndef CERTS_H", "#define CERTS_H", "",
]
for name, fname, desc in items:
    data = (src / fname).read_bytes()
    lines.append("/* %s, %d bytes */" % (desc, len(data)))
    lines.append("static const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
lines.append("#endif /* CERTS_H */")
out.write_text("\n".join(lines) + "\n")
print("wrote %s" % out)
